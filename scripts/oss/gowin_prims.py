"""Writes the Gowin primitives game20k instantiates as empty modules for slang.

Usage: gowin_prims.py <yosys share/gowin dir> <out.v> NAME...
Each NAME is copied from Yosys' cells_sim.v or cells_xtra_gw2a.v with its ports and
parameters, without the body or specify block. A NAME found in neither becomes an empty
stub (for vendor branches of generate blocks that are never built, e.g. Xilinx OSERDESE2).
"""
import re
import sys

lib_dir, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
text = open(f"{lib_dir}/cells_sim.v").read() + open(f"{lib_dir}/cells_xtra_gw2a.v").read()

parts = ["// generated by gowin_prims.py from Yosys' Gowin library\n"]
for name in names:
    m = re.search(rf"^module {name}\b.*?^endmodule", text, re.S | re.M)
    if not m:
        parts.append(f"module {name}; endmodule  // stub, not in the Gowin library\n")
        continue
    body = m.group(0)
    body = re.sub(r"\bspecify\b.*?\bendspecify\b", "", body, flags=re.S)
    keep = []
    for line in body.splitlines():
        s = line.strip()
        # keep the header, port and parameter declarations, drop logic
        if re.match(r"(module|endmodule|input|output|inout|parameter|localparam)\b", s) or s == ");":
            keep.append(line)
        elif keep and not keep[-1].rstrip().endswith(";") and keep[-1].lstrip().startswith("module"):
            keep.append(line)  # continuation of a multi-line module header
    # A parameter with a string default must be declared as string, otherwise slang hands
    # its value on as a bit vector ("27" arrives in gowin_pack as 11001000110111)
    keep = [re.sub(r'^(\s*parameter)(\s+\w+\s*=\s*")', r"\1 string\2", l) for l in keep]
    parts.append("(* blackbox *)\n" + "\n".join(keep) + "\n")
open(out, "w").write("\n".join(parts))
