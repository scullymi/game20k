"""@file
@brief The stepping stone of the BL616: its build into fpga/stone/stone.bin and the C file that
puts it into the firmware.

The stepping stone is an empty bitstream whose header carries the 0xD2 command, the address the
FPGA loads from at the next RECONFIG. The BL616 sends it over JTAG with the address of a slot
set and jumps to the core there, see stone.c in the fork. stone.bin is checked in: the firmware
is built on Linux and Windows with the same bytes, without the FPGA tools."""

from __future__ import annotations

from pathlib import Path

from tools.engine import config, host, toolchain
from tools.engine.flow.build import APICULA_QUIET, YOSYS_ENV, step
from tools.engine.host import StepError

## the stepping stone's sources and its checked-in bitstream, relative to the root
FOLDER = Path("fpga") / "stone"
## the board of the BL616, whose FPGA and flash slots the stepping stone serves
BOARD = Path("boards") / "tangnano20k-singleboard" / "board.toml"
## the head of the 0xD2 command, the four bytes of the address follow, most significant first
D2 = bytes([0xD2, 0x00, 0xFF, 0xFF])


def build(root: Path, out: Path) -> bytes:
    """@brief Builds the stepping stone in out and returns its bitstream. Packed as the cores are
    (sspi_as_gpio, mspi_as_gpio), compressed, with the jump address 0."""
    board = config.load_board(root / BOARD)
    tools = toolchain.locate(root)
    src = root / FOLDER
    out.mkdir(parents=True, exist_ok=True)
    step("yosys")
    synth = f"read_verilog {(src / 'stone.v').as_posix()}; "
    synth += f"synth_gowin -top stone -family {board.synth_family} -json stone.json"
    host.run([tools.yosys, "-q", "-l", out / "yosys.log", "-p", synth], cwd=out, env=YOSYS_ENV)
    step("nextpnr")
    cmd: list[host.Arg] = [tools.nextpnr, "--json", out / "stone.json", "--write", out / "stone_pnr.json"]
    cmd += [
        "--device",
        board.device,
        "--vopt",
        f"family={board.family}",
        "--vopt",
        f"cst={src / 'stone.cst'}",
    ]
    if board.sspi_as_gpio:
        cmd += ["--vopt", "sspi_as_gpio"]
    host.run([*cmd, "-l", out / "nextpnr.log", "-q"], cwd=out)
    step("gowin_pack")
    pack: list[host.Arg] = [tools.python, *APICULA_QUIET, root / "scripts" / "oss" / "gowin_pack_g20k.py"]
    pack += ["-d", board.family, "-c", "--multiboot_address", "0x000000"]
    if board.sspi_as_gpio:
        pack.append("--sspi_as_gpio")
    if board.mspi_as_gpio:
        pack.append("--mspi_as_gpio")
    pack += ["-o", out / "stone.fs", out / "stone_pnr.json"]
    host.run(pack, cwd=out, env={"PYTHONPATH": str(tools.apicula)}, capture=False)
    host.run(
        host.python(root / "scripts" / "oss" / "fs2bin.py", out / "stone.fs", out / "stone.bin"), cwd=out
    )
    bits = (out / "stone.bin").read_bytes()
    d2_offset(bits)  # a bitstream without one 0xD2 command is of no use to the firmware
    return bits


def make(root: Path, check: bool) -> None:
    """@brief Builds the stepping stone into fpga/stone/stone.bin, with check only compares the
    build with the file there."""
    bits = build(root, root / "build" / "stone")
    kept = root / FOLDER / "stone.bin"
    if not check:
        kept.write_bytes(bits)
        print(f"{kept.relative_to(root).as_posix()}: {len(bits)} bytes")
    elif not kept.is_file() or kept.read_bytes() != bits:
        raise StepError(
            f"{kept.relative_to(root).as_posix()} differs from a new build, run: python3 g20k.py stone"
        )
    else:
        print(f"{kept.relative_to(root).as_posix()}: the same as a new build")


def d2_offset(bits: bytes) -> int:
    """@brief Where the one 0xD2 command of a bitstream starts."""
    at = bits.find(D2)
    if at < 0 or bits.find(D2, at + 1) >= 0:
        raise StepError(f"the stepping stone needs one 0xD2 command, it has {bits.count(D2)}")
    if at + len(D2) + 4 > len(bits):
        raise StepError("the stepping stone ends within its 0xD2 command")
    return at


def c_source(bits: bytes, slot_size: int) -> str:
    """@brief The C file of the firmware with the stepping stone, the place of its 0xD2 command and
    the size of a flash slot, see stone.h in the fork."""
    rows = ",\n".join(
        "  " + ", ".join(f"0x{b:02x}" for b in bits[i : i + 16]) for i in range(0, len(bits), 16)
    )
    return (
        "/* Generated by g20k.py firmware from fpga/stone/stone.bin, see tools/engine/stone.py. */\n"
        '#include "stone.h"\n\n'
        f"const unsigned char stone_bits[] = {{\n{rows}\n}};\n"
        f"const size_t stone_size = {len(bits)};\n"
        f"const size_t stone_d2 = {d2_offset(bits)};\n"
        f"const uint32_t stone_slot_bytes = 0x{slot_size:x};\n"
    )


def make_source(root: Path, out: Path) -> Path:
    """@brief Writes the C file of the stepping stone into out and returns its path. The slot size
    comes from the board of the BL616, the bitstream from the checked-in file."""
    board = config.load_board(root / BOARD)
    kept = root / FOLDER / "stone.bin"
    if not kept.is_file():
        raise StepError(f"{kept.relative_to(root).as_posix()} is missing, run: python3 g20k.py stone")
    bits = kept.read_bytes()
    path = out / "stone_data.c"
    out.mkdir(parents=True, exist_ok=True)
    text = c_source(bits, board.flash.slot_size)
    # rewritten only when it changes, so ninja does not rebuild it every time
    if not path.is_file() or path.read_text() != text:
        path.write_text(text)
    return path
